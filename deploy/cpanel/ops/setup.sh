#!/bin/bash
# One-time setup of Darb on the cPanel account (run on the server, from ~/darb-app):
#   bash ops/setup.sh
# Creates ~/darb-app/.env with freshly generated secrets (never printed), the logs and
# backup folders, and registers the Node.js app for darb.aynur.ps with the CloudLinux
# selector. Safe to re-run: an existing .env and an existing app registration are kept.
set -euo pipefail

APP_ROOT="$HOME/darb-app"
DOMAIN="darb.aynur.ps"
NODE_VERSION="22"
ENV_FILE="$APP_ROOT/.env"

umask 077
mkdir -p "$APP_ROOT/logs" "$APP_ROOT/tmp" "$HOME/darb-backups"
chmod 700 "$HOME/darb-backups"

secret() { openssl rand -base64 64 | tr -d '\n/+=' | cut -c1-48; }

if [ -f "$ENV_FILE" ]; then
  echo "Keeping the existing $ENV_FILE"
else
  cat > "$ENV_FILE" <<EOF
# Darb production settings for $DOMAIN. Generated by ops/setup.sh; keep private (chmod 600).
# The owner fills in the two passwords marked FILL IN; everything else was generated here.
APP_ENV="production"
ENABLE_DEMO_FEATURES="false"
APP_RELEASE="set-by-deploy"
PORT="3000"
LOG_LEVEL="info"
TRUST_PROXY="1"
CORS_ORIGINS="https://$DOMAIN"
ADMIN_STATIC_DIR="$APP_ROOT/admin"

# Database (cPanel MySQL). DATABASE_URL is built from these parts by app.js / ops/run.mjs.
DB_HOST="localhost"
DB_PORT="3306"
DB_NAME="aynurzzx_Darb"
DB_USER="aynurzzx_Darb_User"
DB_PASSWORD=""   # leave empty: set it in cPanel > Setup Node.js App > Environment variables

# Email: the cPanel mailbox darb@aynur.ps on this host (outbound Gmail SMTP is blocked here)
EMAIL_DELIVERY="smtp"
SMTP_HOST="mail.aynur.ps"
SMTP_PORT="465"
SMTP_SECURE="tls"
SMTP_USER="darb@aynur.ps"
SMTP_PASSWORD=""   # leave empty: set it in cPanel > Setup Node.js App > Environment variables
EMAIL_FROM_ADDRESS="darb@aynur.ps"
EMAIL_FROM_NAME="Darb"
OTP_PROVIDER="email"

# Sign-in and sessions
JWT_SECRET="$(secret)"
ACCESS_TOKEN_TTL_SECONDS="900"
REFRESH_TOKEN_TTL_DAYS="30"
REFRESH_TOKEN_PEPPER="$(secret)"
ADMIN_SESSION_IDLE_TIMEOUT_SECONDS="1800"
ADMIN_SESSION_ABSOLUTE_TIMEOUT_SECONDS="43200"
AUTH_ACTION_TOKEN_PEPPER="$(secret)"
AUTH_ACTION_TOKEN_KEY_VERSION="1"
GOOGLE_PASSENGER_SIGNUP_MODE="disabled"
GOOGLE_PASSENGER_ALLOWLIST_HMACS=""

# Registration (drivers and shop owners sign up themselves; documents are stored in MySQL)
INVITATIONS_ENABLED="false"
PUBLIC_ONBOARDING_ENABLED="true"
DRIVER_DOCUMENTS_ENABLED="true"
DRIVER_DOCUMENT_RETENTION_DAYS="90"
SUPPORTED_PHONE_REGIONS="PS"
INVITATION_CODE_PEPPER="$(secret)"
INVITATION_CODE_KEY_VERSION="1"
PHONE_DIGEST_PEPPER="$(secret)"
PHONE_DIGEST_KEY_VERSION="1"
OTP_CODE_PEPPER="$(secret)"
OTP_CODE_KEY_VERSION="1"
ONBOARDING_SESSION_PEPPER="$(secret)"
ONBOARDING_SESSION_KEY_VERSION="1"
IDEMPOTENCY_KEY_PEPPER="$(secret)"
IDEMPOTENCY_KEY_VERSION="1"
IDEMPOTENCY_PAYLOAD_PEPPER="$(secret)"
IDEMPOTENCY_PAYLOAD_KEY_VERSION="1"
ABUSE_KEY_PEPPER="$(secret)"
ABUSE_KEY_VERSION="1"
ONBOARDING_TEST_LEGAL_FIXTURES_ENABLED="false"

# Rate limits and health
RATE_LIMIT_GLOBAL_WINDOW_MS="900000"
RATE_LIMIT_GLOBAL_MAX="300"
RATE_LIMIT_LOGIN_WINDOW_MS="900000"
RATE_LIMIT_LOGIN_MAX="10"
READINESS_TIMEOUT_MS="2000"
EOF
  chmod 600 "$ENV_FILE"
  echo "Created $ENV_FILE with new secrets. Fill in DB_PASSWORD and SMTP_PASSWORD before starting."
fi

# Register the Node.js app once (cPanel > Setup Node.js App shows the same entry).
if cloudlinux-selector get --json --interpreter nodejs 2>/dev/null | grep -q '"darb-app"'; then
  echo "Node.js app darb-app is already registered."
else
  cloudlinux-selector create --json --interpreter nodejs --version "$NODE_VERSION" \
    --app-root darb-app --domain "$DOMAIN" --app-uri / --app-mode production --startup-file app.cjs
  echo "Registered the Node.js app for https://$DOMAIN (startup file app.cjs, Node $NODE_VERSION)."
fi
